export const cupidIconNames = Object.freeze(Object.keys(pixels));
export function cupidIcon(name) {
  const source = pixels[name];
  if (!source) throw new Error(`Unknown Cupid icon: ${name}`);
  const rows = source.split("/");
  if (rows.length !== 8 || rows.some((row) => row.length !== 8))
    throw new Error(`Invalid pixel grid: ${name}`);
  const d = rows
    .flatMap((row, y) =>
      [...row].flatMap((cell, x) =>
        cell === "#" ? [`M${x + 1} ${y + 1}h1v1h-1z`] : [],
      ),
    )
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" class="icon cupid-icon" data-icon="${name}" viewBox="0 0 10 10" width="30" height="30" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path d="${d}"/></svg>`;
}

