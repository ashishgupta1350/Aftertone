"""Export original Cupid prototype vectors and pixel symbols into native Android resources."""
from pathlib import Path
import json
import re
import shutil
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
RES = ROOT / 'app/src/main/res'
KOTLIN = ROOT / 'app/src/main/java/com/prism/music/ui/theme'
A = '{http://schemas.android.com/apk/res/android}'
ET.register_namespace('android', 'http://schemas.android.com/apk/res/android')
palettes = json.loads((HERE / 'tokens.json').read_text())['palettes']

def native_room(palette, destination):
    source = ET.parse(HERE / 'assets/cupid/room.svg').getroot()
    target = ET.Element('vector', {A+'width': '360dp', A+'height': '320dp', A+'viewportWidth': '360', A+'viewportHeight': '320'})

    def color(value):
        match = re.fullmatch(r'var\(--cupid-([a-z-]+),(#[0-9a-fA-F]+)\)', value)
        if match:
            key = re.sub(r'-([a-z])', lambda m: m[1].upper(), match[1])
            value = palette.get(key, match[2])
        return '#00000000' if value == 'none' else value

    def walk(element, parent, inherited):
        attrs = inherited | {k: v for k, v in element.attrib.items() if k in ('fill', 'stroke', 'stroke-width', 'fill-opacity', 'stroke-opacity')}
        attrs['opacity'] = str(float(inherited.get('opacity', 1)) * float(element.get('opacity', 1)))
        tag = element.tag.split('}')[-1]
        if tag in ('svg', 'g'):
            group = parent
            transform = element.get('transform', '')
            if transform:
                group = ET.SubElement(parent, 'group')
                for operation, args in re.findall(r'(translate|scale)\(([^)]+)\)', transform):
                    values = re.split(r'[ ,]+', args.strip())
                    if operation == 'translate':
                        group.set(A+'translateX', values[0]); group.set(A+'translateY', values[1] if len(values)>1 else '0')
                    else:
                        group.set(A+'scaleX', values[0]); group.set(A+'scaleY', values[1] if len(values)>1 else values[0])
            for child in element:
                walk(child, group, attrs)
            return
        if tag == 'circle':
            cx, cy, r = (float(element.get(k, '0')) for k in ('cx', 'cy', 'r'))
            data = f'M{cx-r},{cy}a{r},{r} 0,1 0 {2*r},0a{r},{r} 0,1 0 {-2*r},0'
        elif tag == 'path':
            data = element.get('d')
        else:
            raise ValueError(tag)
        path = ET.SubElement(parent, 'path', {A+'pathData': data})
        path.set(A+'fillColor', color(attrs.get('fill', '#000000')))
        path.set(A+'fillAlpha', str(float(attrs.get('opacity', 1)) * float(attrs.get('fill-opacity', 1))))
        if 'stroke' in attrs:
            path.set(A+'strokeColor', color(attrs['stroke']))
            path.set(A+'strokeWidth', attrs.get('stroke-width', '1'))
            path.set(A+'strokeAlpha', str(float(attrs.get('opacity', 1)) * float(attrs.get('stroke-opacity', 1))))
    walk(source, target, {})
    ET.indent(target)
    ET.ElementTree(target).write(destination, encoding='utf-8', xml_declaration=True)

drawable = RES / 'drawable'
drawable.mkdir(parents=True, exist_ok=True)
for name, palette in [('day', 'cupidday'), ('night', 'cupidnight')]:
    native_room(palettes[palette], drawable / f'cupid_room_{name}.xml')

source = (HERE / 'cupid-icons.mjs').read_text()
pixels = re.findall(r'\b(\w+):\s*"([.#/]+)"', source.split('export const')[0])
assert len(pixels) == 36
rows = '\n'.join(f'        "{name}" to "{bitmap}",' for name, bitmap in pixels)
(KOTLIN / 'CupidPixelData.kt').write_text('// Generated by design/android-prototype/export-android-assets.py. Original CC0 symbols.\npackage com.prism.music.ui.theme\n\ninternal object CupidPixelData {\n    val pixels = mapOf(\n'+rows+'\n    )\n}\n')
(RES / 'font').mkdir(exist_ok=True)
shutil.copyfile(HERE / 'assets/cupid/lovebit.ttf', RES / 'font/lovebit.ttf')
print('Exported day/night room vectors, 36 pixel symbols and Lovebit font.')
